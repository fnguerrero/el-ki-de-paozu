// los retratos de las charlas, que tienen que verse grandes.
function dibujarMatrizEscala(m, x, y, facing, tintas, esc) {
  const alto = m.length, ancho = m[0].length;
  const ox = Math.round(x) - Math.round((ancho * esc) / 2);
  const oy = Math.round(y) - alto * esc;
  for (let fy = 0; fy < alto; fy++) {
    const fila = m[fy];
    for (let fx = 0; fx < ancho; fx++) {
      const ch = fila[facing < 0 ? ancho - 1 - fx : fx];
      if (ch === '.') continue;
      const c = (tintas && tintas[ch]) || TINTA[ch];
      if (c) Px.rect(ox + fx * esc, oy + fy * esc, esc, esc, c);
    }
  }
}

