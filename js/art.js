// Baja el brillo de un color conservando su tono, y lo tira un poco hacia el
// azul de la sombra. Un apagado plano deja todo marron y los personajes se
// vuelven irreconocibles.
function enSombra(hex, fuerza) {
  const f = fuerza === undefined ? 0.45 : fuerza;
  const n = parseInt(hex.slice(1), 16);
  const r = Math.round(((n >> 16) & 255) * f + 10 * (1 - f));
  const g = Math.round(((n >> 8) & 255) * f + 14 * (1 - f));
  const b = Math.round((n & 255) * f + 34 * (1 - f));
  return '#' + ((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1);
}

// Version apagada de la paleta: se usa para el personaje que NO esta hablando
// en una charla.
const TINTA_APAGADA = (function () {
  const t = {};
  Object.keys(TINTA).forEach(k => {
    if (!TINTA[k]) return;
    // El contorno se apaga mas, el relleno menos: asi la silueta sigue nitida
    t[k] = enSombra(TINTA[k], k === 'K' ? 0.35 : 0.62);
  });
  return t;
})();

