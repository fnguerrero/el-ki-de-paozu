function dibujarMatriz(m, x, y, facing, tintas) {
  const alto = m.length, ancho = m[0].length;
  const ox = Math.round(x) - (ancho >> 1);
  const oy = Math.round(y) - alto;
  for (let fy = 0; fy < alto; fy++) {
    const fila = m[fy];
    for (let fx = 0; fx < ancho; fx++) {
      const ch = fila[facing < 0 ? ancho - 1 - fx : fx];
      if (ch === '.') continue;
      const c = (tintas && tintas[ch]) || TINTA[ch];
      if (c) Px.punto(ox + fx, oy + fy, c);
    }
  }
}

